// mergeInclude ensures the include: sequence contains an entry for
// the fullsend pipeline file. If the key doesn't exist, it creates one.
func mergeInclude(root *yaml.Node) error {
	includeVal := findMappingValue(root, "include")
	if includeVal == nil {
		// Create include: key with a sequence containing our entry.
		keyNode := &yaml.Node{Kind: yaml.ScalarNode, Value: "include", Tag: "!!str"}
		entry := makeIncludeEntry(fullsendPipelineInclude)
		seqNode := &yaml.Node{
			Kind:    yaml.SequenceNode,
			Tag:     "!!seq",
			Content: []*yaml.Node{entry},
		}
		// Prepend include at the top of the mapping.
		root.Content = append([]*yaml.Node{keyNode, seqNode}, root.Content...)
		return nil
	}
	includeVal.Style = 0

	if includeVal.Kind != yaml.SequenceNode {
		// include: might be a single scalar or mapping. Wrap it in a
		// sequence so we can append our entry.
		wrapped := &yaml.Node{}
		*wrapped = *includeVal
		includeVal.Kind = yaml.SequenceNode
		includeVal.Tag = "!!seq"
		includeVal.Value = ""
		includeVal.Content = []*yaml.Node{wrapped}
	}

	// Check if our include is already present.
	if slices.ContainsFunc(includeVal.Content, isFullsendPipelineInclude) {
		return nil // Already present, idempotent.
	}

	// Append our include entry.
	entry := makeIncludeEntry(fullsendPipelineInclude)
	includeVal.Content = append(includeVal.Content, entry)
	return nil
}

// makeIncludeEntry creates a YAML mapping node for {local: '<path>'}.
func makeIncludeEntry(path string) *yaml.Node {
	return &yaml.Node{
		Kind: yaml.MappingNode,
		Tag:  "!!map",
		Content: []*yaml.Node{
			{Kind: yaml.ScalarNode, Value: "local", Tag: "!!str"},
			{Kind: yaml.ScalarNode, Value: path, Tag: "!!str", Style: yaml.SingleQuotedStyle},
		},
	}
}

// includeMappingAllowedKeys are the only keys, besides "local", that
// isFullsendPipelineInclude tolerates inside an include-mapping item
// without failing closed. GitLab supports several other include-location
// keys on the same mapping form ("<<" merge, "file", "project", "remote",
// "template", "component") that name a different include entirely — a
// mapping combining one of those with "local:" can't be trusted to
// resolve to the fullsend include and nothing else — so anything not in
// this allowlist is treated the same as an unclassifiable key.
var includeMappingAllowedKeys = map[string]bool{
	"local":     true,
	"rules":     true,
	"inputs":    true,
	"integrity": true,
}

// isFullsendPipelineInclude checks whether a YAML node is an include
// entry pointing to the fullsend pipeline file.
//
// The mapping form (`{local: ...}`) walks every key/value pair rather than
// stopping at the first "local" match: gopkg.in/yaml.v3 preserves
// duplicate mapping keys as separate Content pairs instead of collapsing
// them, and GitLab/Psych is last-wins, so `{local: fullsend-pipeline.yml,
// local: other.yml}` would otherwise be misclassified as the fullsend
// include by a first-match check even though the second, real value wins.
// Key classification is delegated to classifyTopLevelKey (the same
// alias-resolving, tag-checking classifier used for top-level and job
// keys) so an alias-keyed or non-core-tagged key here can't be silently
// treated as an ordinary "local" key. A key outside includeMappingAllowedKeys
// — including one carrying interpolation syntax that might evaluate to
// "local" or another location key at pipeline time, see
// hasInterpolationSyntax — is treated the same as unclassifiable rather
// than silently skipped via continue: it might be another include-location
// key (or a duplicate "local") this check would otherwise miss. A
// duplicated "local" key, an unclassifiable key, and a not-allowlisted key
// all fail closed by returning false — treat this item as not (confirmed
// as) the fullsend pipeline include — since which value GitLab would
// actually resolve to can't be determined with confidence.
func isFullsendPipelineInclude(node *yaml.Node) bool {
	if node.Kind == yaml.ScalarNode {
		return node.Value == fullsendPipelineInclude
	}
	if node.Kind != yaml.MappingNode {
		return false
	}
	localCount := 0
	isFullsend := false
	for i := 0; i+1 < len(node.Content); i += 2 {
		name, ok := classifyTopLevelKey(node.Content[i])
		if !ok || hasInterpolationSyntax(name) || !includeMappingAllowedKeys[name] {
			// An unclassifiable key (an alias, a non-core-tagged key, or a
			// non-scalar key), a key carrying interpolation syntax, or a
			// key that isn't a known-safe include-mapping key can't be
			// ruled out as another "local" occurrence or a different
			// include-location key entirely. Fail closed.
			return false
		}
		if name != "local" {
			continue
		}
		localCount++
		value, ok := isLiteralScalarValue(node.Content[i+1])
		isFullsend = ok && value == fullsendPipelineInclude
	}
	if localCount > 1 {
		return false
	}
	return isFullsend
}

// mergeStages appends fullsend's stages to an existing stages: array,
// deduplicating entries that are already present. When no stages: key
// exists, the function is a no-op — the included pipeline file's
// stages will be used by GitLab automatically.
func mergeStages(root *yaml.Node) {
	stagesVal := findMappingValue(root, "stages")
	if stagesVal == nil || stagesVal.Kind != yaml.SequenceNode {
		return
	}

	// Collect existing stage names for deduplication.
	existing := make(map[string]bool)
	for _, item := range stagesVal.Content {
		if item.Kind == yaml.ScalarNode {
			existing[item.Value] = true
		}
	}

	// Append missing fullsend stages.
	for _, stage := range fullsendStages {
		if !existing[stage] {
			stagesVal.Content = append(stagesVal.Content, &yaml.Node{
				Kind:  yaml.ScalarNode,
				Value: stage,
				Tag:   "!!str",
			})
		}
	}
}

// mergeWorkflow ensures an existing workflow: block contains fullsend's
// rules and auto_cancel settings. When no workflow: block exists, it is
// left absent — fullsend's jobs have their own rules: that self-filter
// by pipeline source, and creating a workflow: block would gate all
// pipelines to only fullsend's sources, breaking push-triggered CI.
func mergeWorkflow(root *yaml.Node) error {
	workflowVal := findMappingValue(root, "workflow")
	if workflowVal == nil {
		// No existing workflow block — leave it absent so the repo's
		// push-triggered pipelines continue to run.
		return nil
	}

	if workflowVal.Kind != yaml.MappingNode {
		return fmt.Errorf("workflow: is not a mapping")
	}

	// Ensure auto_cancel.on_new_commit: none is set.
	mergeAutoCancel(workflowVal)

	// Merge rules.
	mergeWorkflowRules(workflowVal)

	return nil
}

// mergeAutoCancel ensures workflow.auto_cancel.on_new_commit: none.
func mergeAutoCancel(workflow *yaml.Node) {
	acVal := findMappingValue(workflow, "auto_cancel")
	if acVal == nil {
		// Create auto_cancel block.
		keyNode := &yaml.Node{Kind: yaml.ScalarNode, Value: "auto_cancel", Tag: "!!str"}
		valNode := &yaml.Node{
			Kind: yaml.MappingNode,
			Tag:  "!!map",
			Content: []*yaml.Node{
				{Kind: yaml.ScalarNode, Value: "on_new_commit", Tag: "!!str"},
				{Kind: yaml.ScalarNode, Value: "none", Tag: "!!str"},
			},
		}
		workflow.Content = append(workflow.Content, keyNode, valNode)
		return
	}

	if acVal.Kind != yaml.MappingNode {
		return
	}

	oncVal := findMappingValue(acVal, "on_new_commit")
	if oncVal == nil {
		acVal.Content = append(acVal.Content,
			&yaml.Node{Kind: yaml.ScalarNode, Value: "on_new_commit", Tag: "!!str"},
			&yaml.Node{Kind: yaml.ScalarNode, Value: "none", Tag: "!!str"},
		)
	}
	// If on_new_commit exists, leave the user's value alone.
}

// debugTraceDenyRuleSatisfied reports whether rules already contains a
// correctly-shaped CI_DEBUG_TRACE deny-before-admit guard: if: equal to
// debugTraceDenyRuleIf, when: equal to "never", and positioned first in
// the list. GitLab's default when: (when omitted) is "always", not
// "never", and rules are evaluated first-match, so a same-if: rule with
// the wrong when:, or one that isn't first, would let a debug-trace
// pipeline reach whatever rule precedes it — that rule is not treated as
// satisfying the guard.
func debugTraceDenyRuleSatisfied(rules []*yaml.Node) bool {
	if len(rules) == 0 {
		return false
	}
	first := rules[0]
	if first.Kind != yaml.MappingNode {
		return false
	}
	ifVal := findMappingValue(first, "if")
	whenVal := findMappingValue(first, "when")
	return ifVal != nil && ifVal.Value == debugTraceDenyRuleIf &&
		whenVal != nil && whenVal.Value == "never"
}

// removeRuleByIf returns rules with any mapping entry whose if: equals
// ifCond removed. Used when backfilling a corrected deny-before-admit
// rule to replace an existing same-if: rule that has the wrong when: or
// the wrong position, rather than leaving a duplicate if: condition in
// the merged rules list.
func removeRuleByIf(rules []*yaml.Node, ifCond string) []*yaml.Node {
	kept := make([]*yaml.Node, 0, len(rules))
	for _, item := range rules {
		if item.Kind == yaml.MappingNode {
			if v := findMappingValue(item, "if"); v != nil && v.Value == ifCond {
				continue
			}
		}
		kept = append(kept, item)
	}
	return kept
}

// mergeWorkflowRules merges fullsend's rules into workflow.rules,
// deduplicating by if: condition. Deny-before-admit rules (When=never)
// are prepended so first-match evaluation sees them before any admit
// rule that was already present on an enrolled repo — a same-if: rule
// with the wrong when: or the wrong position does not count as already
// present (see debugTraceDenyRuleSatisfied) and is replaced rather than
// left in place, so the merged list never carries a duplicate if:
// condition for the same guard. Other missing rules are appended as
// before, deduplicated by if: alone.
func mergeWorkflowRules(workflow *yaml.Node) {
	rulesVal := findMappingValue(workflow, "rules")
	if rulesVal == nil {
		// Create rules sequence.
		keyNode := &yaml.Node{Kind: yaml.ScalarNode, Value: "rules", Tag: "!!str"}
		seqNode := &yaml.Node{Kind: yaml.SequenceNode, Tag: "!!seq"}
		for _, r := range fullsendWorkflowRules {
			seqNode.Content = append(seqNode.Content, makeRuleNode(r))
		}
		workflow.Content = append(workflow.Content, keyNode, seqNode)
		return
	}

	if rulesVal.Kind != yaml.SequenceNode {
		return
	}

	// Collect existing if: conditions for deduplication of admit rules
	// (When == "").
	existing := make(map[string]bool)
	for _, item := range rulesVal.Content {
		if item.Kind == yaml.MappingNode {
			if v := findMappingValue(item, "if"); v != nil {
				existing[v.Value] = true
			}
		}
	}

	var prepend []*yaml.Node
	var appendMissing []*yaml.Node
	for _, r := range fullsendWorkflowRules {
		if r.When == "never" {
			if debugTraceDenyRuleSatisfied(rulesVal.Content) {
				continue
			}
			// A same-if: rule with the wrong when: or wrong position is
			// superseded by the correctly-shaped rule prepended below,
			// rather than left in place as a duplicate if: condition.
			rulesVal.Content = removeRuleByIf(rulesVal.Content, r.If)
			prepend = append(prepend, makeRuleNode(r))
			continue
		}
		if existing[r.If] {
			continue
		}
		appendMissing = append(appendMissing, makeRuleNode(r))
	}
	rulesVal.Content = append(prepend, append(rulesVal.Content, appendMissing...)...)
}

// makeRuleNode creates a YAML mapping node for a workflow rule.
func makeRuleNode(r workflowRule) *yaml.Node {
	content := []*yaml.Node{
		{Kind: yaml.ScalarNode, Value: "if", Tag: "!!str"},
		{Kind: yaml.ScalarNode, Value: r.If, Tag: "!!str"},
	}
	if r.When != "" {
		content = append(content,
			&yaml.Node{Kind: yaml.ScalarNode, Value: "when", Tag: "!!str"},
			&yaml.Node{Kind: yaml.ScalarNode, Value: r.When, Tag: "!!str"},
		)
	}
	return &yaml.Node{
		Kind:    yaml.MappingNode,
		Tag:     "!!map",
		Content: content,
	}
}

// removeInclude removes the fullsend pipeline include entry from
// the include: sequence. If the sequence becomes empty, removes the
// include: key entirely.
// gitlabRootHasOtherIncludes reports whether root's include: list
// references any file besides the fullsend pipeline include. Call this
// before removeInclude strips fullsend's own entry. UnmergeGitLabCI has no
// way to fetch and scan a surviving included file's content for $STAGE
// consumers, so its mere presence is treated as a potential consumer —
// see the review finding on the STAGE bridge/input removal missing
// included-file consumers.
func gitlabRootHasOtherIncludes(root *yaml.Node) bool {
	include := findMappingValue(root, "include")
	if include == nil {
		return false
	}
	items := include.Content
	if include.Kind != yaml.SequenceNode {
		items = []*yaml.Node{include}
	}
	for _, item := range items {
		if !isFullsendPipelineInclude(item) {
			return true
		}
	}
	return false
}

func removeInclude(root *yaml.Node) {
	includeIdx := findMappingKeyIndex(root, "include")
	if includeIdx < 0 {
		return
	}
	includeVal := root.Content[includeIdx+1]

	if includeVal.Kind == yaml.SequenceNode {
		var kept []*yaml.Node
		for _, item := range includeVal.Content {
			if !isFullsendPipelineInclude(item) {
				kept = append(kept, item)
			}
		}
		if len(kept) == 0 {
			// Remove the entire include: key.
			root.Content = append(root.Content[:includeIdx], root.Content[includeIdx+2:]...)
		} else {
			includeVal.Content = kept
		}
	} else if isFullsendPipelineInclude(includeVal) {
		root.Content = append(root.Content[:includeIdx], root.Content[includeIdx+2:]...)
	}
}

// removeStages removes fullsend's stages from the stages: array. If
// the array becomes empty, removes the stages: key entirely.
func removeStages(root *yaml.Node) {
	stagesIdx := findMappingKeyIndex(root, "stages")
	if stagesIdx < 0 {
		return
	}
	stagesVal := root.Content[stagesIdx+1]
	if stagesVal.Kind != yaml.SequenceNode {
		return
	}

	fsStages := make(map[string]bool, len(fullsendStages))
	for _, stage := range fullsendStages {
		fsStages[stage] = true
	}

	var kept []*yaml.Node
	for _, item := range stagesVal.Content {
		if item.Kind == yaml.ScalarNode && fsStages[item.Value] {
			continue
		}
		kept = append(kept, item)
	}

	if len(kept) == 0 {
		root.Content = append(root.Content[:stagesIdx], root.Content[stagesIdx+2:]...)
	} else {
		stagesVal.Content = kept
	}
}

// removeWorkflowRules removes fullsend's workflow:rules entries. If
// the workflow block has no remaining keys, removes it entirely.
func removeWorkflowRules(root *yaml.Node) {
	wfIdx := findMappingKeyIndex(root, "workflow")
	if wfIdx < 0 {
		return
	}
	workflowVal := root.Content[wfIdx+1]
	if workflowVal.Kind != yaml.MappingNode {
		return
	}

	// Build a set of fullsend rule conditions for matching.
	fsRules := make(map[string]bool)
	for _, r := range unmergeWorkflowRules {
		fsRules[r.If] = true
	}
	// When the block carries fullsend's provenance marker (workflow.name),
	// fullsend also owns any obsolete rule it installed in an earlier
	// version, so remove those too — otherwise a fresh-install uninstall
	// leaves the orphaned merge_request_event rule behind, producing the
	// empty MR pipelines #7322 set out to eliminate. Without the marker the
	// obsolete rule is indistinguishable from a repo's own MR gate and is
	// left in place (see unmergeWorkflowRules).
	if gitlabCIWorkflowIsFullsendOwned(workflowVal) {
		for _, r := range obsoleteGitLabWorkflowRules {
			fsRules[r.If] = true
		}
	}

	// Remove matching rules from workflow.rules.
	rulesIdx := findMappingKeyIndex(workflowVal, "rules")
	if rulesIdx >= 0 {
		rulesVal := workflowVal.Content[rulesIdx+1]
		if rulesVal.Kind == yaml.SequenceNode {
			var kept []*yaml.Node
			for _, item := range rulesVal.Content {
				if item.Kind == yaml.MappingNode {
					if v := findMappingValue(item, "if"); v != nil && fsRules[v.Value] {
						continue
					}
				}
				kept = append(kept, item)
			}
			if len(kept) == 0 {
				// Remove rules: key entirely.
				workflowVal.Content = append(
					workflowVal.Content[:rulesIdx],
					workflowVal.Content[rulesIdx+2:]...)
			} else {
				rulesVal.Content = kept
			}
		}
	}

	// Remove workflow.name if it matches the fullsend pattern.
	nameIdx := findMappingKeyIndex(workflowVal, "name")
	if nameIdx >= 0 {
		nameVal := workflowVal.Content[nameIdx+1]
		if strings.HasPrefix(nameVal.Value, fullsendWorkflowNamePrefix) {
			workflowVal.Content = append(
				workflowVal.Content[:nameIdx],
				workflowVal.Content[nameIdx+2:]...)
		}
	}

	// Remove auto_cancel.on_new_commit if it's "none" (fullsend's value).
	acIdx := findMappingKeyIndex(workflowVal, "auto_cancel")
	if acIdx >= 0 {
		acVal := workflowVal.Content[acIdx+1]
		if acVal.Kind == yaml.MappingNode {
			oncIdx := findMappingKeyIndex(acVal, "on_new_commit")
			if oncIdx >= 0 && acVal.Content[oncIdx+1].Value == "none" {
				acVal.Content = append(acVal.Content[:oncIdx], acVal.Content[oncIdx+2:]...)
			}
			if len(acVal.Content) == 0 {
				workflowVal.Content = append(
					workflowVal.Content[:acIdx],
					workflowVal.Content[acIdx+2:]...)
			}
		}
	}

	// If workflow block is empty, remove it.
	if len(workflowVal.Content) == 0 {
		root.Content = append(root.Content[:wfIdx], root.Content[wfIdx+2:]...)
	}
}

// findMappingValue returns the value node for a key in a mapping node,
// or nil if not found.
func findMappingValue(mapping *yaml.Node, key string) *yaml.Node {
	idx := findMappingKeyIndex(mapping, key)
	if idx < 0 {
		return nil
	}
	return mapping.Content[idx+1]
}

// findMappingKeyIndex returns the index of a key in a mapping node's
// Content slice, or -1 if not found.
func findMappingKeyIndex(mapping *yaml.Node, key string) int {
	for i := 0; i+1 < len(mapping.Content); i += 2 {
		if mapping.Content[i].Value == key {
			return i
		}
	}
	return -1
}

// marshalNode marshals a yaml.Node tree back to YAML bytes.
func marshalNode(doc *yaml.Node) ([]byte, error) {
	var buf bytes.Buffer
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(doc); err != nil {
		return nil, fmt.Errorf("marshaling YAML: %w", err)
	}
	if err := enc.Close(); err != nil {
		return nil, fmt.Errorf("closing YAML encoder: %w", err)
	}
	return buf.Bytes(), nil
}

// unmergeGitLabRootCI fetches the existing .gitlab-ci.yml from the repo
// and removes fullsend's entries. Returns the cleaned content, or nil
// if the file should be deleted entirely.
func unmergeGitLabRootCI(ctx context.Context, client forge.Client, owner, repo string) ([]byte, error) {
	existing, err := client.GetFileContent(ctx, owner, repo, ".gitlab-ci.yml")
	if err != nil {
		if forge.IsNotFound(err) {
			return nil, nil // Nothing to clean up.
		}
		return nil, fmt.Errorf("reading .gitlab-ci.yml for cleanup: %w", err)
	}
	return UnmergeGitLabCI(existing)
}
