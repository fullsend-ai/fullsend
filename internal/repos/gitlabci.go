// gitlabVariableBridgesInput reports whether variables declares varName
// with exactly the "$[[ inputs.<inputName> ]]" bridge expression required
// to forward that pipeline input into the job's environment, accepting
// either GitLab's plain-scalar variable syntax or its extended
// ({value:, expand:}) form.
func gitlabVariableBridgesInput(variables *yaml.Node, varName, inputName string) bool {
	return gitlabVariableBridgesInputExpand(variables, varName, inputName, false)
}

// gitlabVariableBridgesInputNonExpanding is the strict form of
// gitlabVariableBridgesInput: it additionally requires the extended
// ({value:, expand: false}) mapping with an explicit boolean false, so
// caller-controlled dispatch metadata is never variable-expanded before
// dispatch authentication. A scalar bridge, a missing expand key, or
// expand: true all fail.
func gitlabVariableBridgesInputNonExpanding(variables *yaml.Node, varName, inputName string) bool {
	return gitlabVariableBridgesInputExpand(variables, varName, inputName, true)
}

func gitlabVariableBridgesInputExpand(variables *yaml.Node, varName, inputName string, requireNoExpand bool) bool {
	want := "$[[ inputs." + inputName + " ]]"
	value := findMappingValue(variables, varName)
	if value == nil {
		return false
	}
	if value.Kind == yaml.ScalarNode {
		return !requireNoExpand && value.Value == want
	}
	if value.Kind == yaml.MappingNode {
		inner := findMappingValue(value, "value")
		if inner == nil || inner.Kind != yaml.ScalarNode || inner.Value != want {
			return false
		}
		if !requireNoExpand {
			return true
		}
		expand := findMappingValue(value, "expand")
		return expand != nil && expand.Kind == yaml.ScalarNode && expand.Tag == "!!bool" && expand.Value == "false"
	}
	return false
}

// gitlabAgentBridgesDispatchInputs reports whether the committed managed agent
// job's variables: block bridges every dispatch
// input into its corresponding job variable using the exact
// "$[[ inputs.<name> ]]" form run-agent-job.sh and HMAC verification
// depend on. Every bridge must be an extended mapping with an explicit
// expand: false, so caller-controlled metadata is not variable-expanded
// before dispatch authentication.
//
// gitlabWrapperHasDispatchInputs only checks that the agent's spec:inputs
// header declares the required input names — a complete header with a
// blank or stale EVENT_PAYLOAD_CHUNK_NN (or any other) bridge, left behind
// by an unmerged repair MR, would still pass that check. The committed
// agent would then silently drop signed payload data and dispatches would
// fail HMAC verification, even though gitlabPollAndAgentTemplatesLanded
// reported the repair as landed — see the review finding on this guard's
// incomplete consumption check.
func gitlabAgentBridgesDispatchInputs(content []byte) bool {
	job, ok := gitlabJobNode(content, fullsendAgentJobName)
	if !ok {
		return false
	}
	variables, ok := effectiveMappingValue(job, "variables")
	if !ok || variables == nil {
		return false
	}
	variables = resolveAlias(variables)
	if variables == nil || variables.Kind != yaml.MappingNode || duplicateMappingKeyProblem(variables) != "" {
		return false
	}
	for varName, inputName := range gitlabAgentInputVariableBridge {
		if !gitlabVariableBridgesInputNonExpanding(variables, varName, inputName) {
			return false
		}
	}
	return true
}

// gitlabPollAndAgentTemplatesLanded reports whether the committed
// .gitlab/ci/fullsend-agent.yml and fullsend-poll.yml on the default
// branch already carry content compatible with typed dispatch: the
// agent template declares the same pipeline-input contract as the
// wrapper and actually bridges every input into the job variable
// run-agent-job.sh and HMAC verification read, and the poll template
// selects FULLSEND_POLL_MODE from the schedule identity
// (CI_PIPELINE_SCHEDULE_DESCRIPTION) rather than a pipeline variable.
//
// GitLabUsesTypedDispatch only inspects the wrapper
// (fullsendPipelineInclude). Normal scaffold delivery commits the
// wrapper, root, agent, and poll templates together, but a wrapper that
// already landed as typed in an earlier run does not guarantee these
// sibling templates did too: an unmerged repair MR touching only the
// agent or poll template can leave them stale while the wrapper remains
// typed. activateGitLabTypedDispatch must not enforce the
// pipeline-variable restriction against that stale state —
// see the review finding at gitlab_pipeline_var_restriction.go.
func gitlabPollAndAgentTemplatesLanded(ctx context.Context, client forge.Client, owner, repo string) (bool, error) {
	agent, err := client.GetFileContent(ctx, owner, repo, fullsendAgentTemplatePath)
	if forge.IsNotFound(err) {
		return false, nil
	}
	if err != nil {
		return false, fmt.Errorf("reading %s: %w", fullsendAgentTemplatePath, err)
	}
	if !gitlabWrapperHasDispatchInputs(agent) {
		return false, nil
	}
	if !gitlabAgentBridgesDispatchInputs(agent) {
		return false, nil
	}

	poll, err := client.GetFileContent(ctx, owner, repo, fullsendPollTemplatePath)
	if forge.IsNotFound(err) {
		return false, nil
	}
	if err != nil {
		return false, fmt.Errorf("reading %s: %w", fullsendPollTemplatePath, err)
	}
	for _, spec := range PipelineScheduleSpecs() {
		if !bytes.Contains(poll, []byte(fmt.Sprintf("CI_PIPELINE_SCHEDULE_DESCRIPTION == %q", spec.Description))) {
			return false, nil
		}
	}
	return true, nil
}

func validateGitLabTypedContract(wrapper []byte) error {
	if !bytes.Contains(wrapper, []byte("# fullsend-input-contract: literal-scheduled-v2")) {
		return fmt.Errorf("%w: pinned typed GitLab scaffold lacks the literal-variable and variable-free schedule contract; upgrade the pin before activation", errGitLabIncompatibleWrapper)
	}
	if !gitlabWrapperForwardsDispatchInputs(wrapper) {
		return fmt.Errorf("%w: typed GitLab wrapper does not forward every dispatch input to %s via its matching $[[ inputs.<name> ]] expression; repair the wrapper before activation", errGitLabIncompatibleWrapper, fullsendAgentTemplatePath)
	}
	return nil
}

// gitlabWrapperForwardsDispatchInputs reports whether the wrapper's include
// of the agent template forwards every dispatch input through the matching
// "$[[ inputs.<name> ]]" expression. Declarations and the contract marker
// alone do not guarantee this intermediate hop: a wrapper that forwards an
// input (e.g. an event_payload_chunk_NN) as a blank or stale value would
// drop part of the signed payload and fail HMAC verification.
func gitlabWrapperForwardsDispatchInputs(wrapper []byte) bool {
	docs, err := decodeGitLabDocuments(wrapper)
	if err != nil || len(docs) != 2 {
		return false
	}
	root := docs[1].Content[0]
	if root.Kind != yaml.MappingNode {
		return false
	}
	include := findMappingValue(root, "include")
	if include == nil {
		return false
	}
	items := include.Content
	if include.Kind != yaml.SequenceNode {
		items = []*yaml.Node{include}
	}
	for _, item := range items {
		if item.Kind != yaml.MappingNode {
			continue
		}
		local := findMappingValue(item, "local")
		if local == nil {
			continue
		}
		if value, ok := isLiteralScalarValue(local); !ok || value != fullsendAgentTemplatePath {
			continue
		}
		inputs := findMappingValue(item, "inputs")
		if inputs == nil || inputs.Kind != yaml.MappingNode {
			return false
		}
		for _, name := range gitlabDispatchInputNames {
			value := findMappingValue(inputs, name)
			if value == nil || value.Kind != yaml.ScalarNode || value.Value != "$[[ inputs."+name+" ]]" {
				return false
			}
		}
		return true
	}
	return false
}

func marshalGitLabDocuments(docs []*yaml.Node) ([]byte, error) {
	var out bytes.Buffer
	encoder := yaml.NewEncoder(&out)
	encoder.SetIndent(2)
	for _, doc := range docs {
		if err := encoder.Encode(doc); err != nil {
			return nil, fmt.Errorf("encoding .gitlab-ci.yml document: %w", err)
		}
	}
	if err := encoder.Close(); err != nil {
		return nil, fmt.Errorf("closing .gitlab-ci.yml encoder: %w", err)
	}
	return out.Bytes(), nil
}

// mergeGitLabInputContract installs the root spec:inputs document and the
// include:inputs forwarding map. It is deliberately part of the merge path,
// rather than only the embedded fixture, so fresh installs and upgrades of
// user-owned roots receive the same contract.
func mergeGitLabInputContract(docs []*yaml.Node, contract *yaml.Node) ([]*yaml.Node, error) {
	clearYAMLComments(contract)
	if len(docs) > 1 {
		if err := mergeSpecInputs(docs[0].Content[0], contract); err != nil {
			return nil, err
		}
	} else {
		docs = append([]*yaml.Node{{Kind: yaml.DocumentNode, Content: []*yaml.Node{contract}}}, docs...)
	}
	return docs, nil
}

func clearYAMLComments(node *yaml.Node) {
	if node == nil {
		return
	}
	node.HeadComment, node.LineComment, node.FootComment = "", "", ""
	for _, child := range node.Content {
		clearYAMLComments(child)
	}
}

func mergeSpecInputs(existing, fixture *yaml.Node) error {
	if existing.Kind != yaml.MappingNode {
		return fmt.Errorf("GitLab spec header must be a mapping")
	}
	fixtureSpec := findMappingValue(fixture, "spec")
	spec := findMappingValue(existing, "spec")
	if spec == nil {
		existing.Content = append(existing.Content, scalarNode("spec"), fixtureSpec)
		return nil
	}
	if spec.Kind != yaml.MappingNode {
		return fmt.Errorf("spec: must be a mapping")
	}
	inputs := findMappingValue(spec, "inputs")
	fixtureInputs := findMappingValue(fixtureSpec, "inputs")
	if inputs == nil {
		spec.Content = append(spec.Content, scalarNode("inputs"), fixtureInputs)
		return nil
	}
	if inputs.Kind != yaml.MappingNode {
		return fmt.Errorf("spec:inputs must be a mapping")
	}
	for i := 0; i+1 < len(fixtureInputs.Content); i += 2 {
		name, definition := fixtureInputs.Content[i].Value, fixtureInputs.Content[i+1]
		if found := findMappingValue(inputs, name); found != nil {
			var a, b any
			if err := found.Decode(&a); err != nil {
				return fmt.Errorf("decoding input %q: %w", name, err)
			}
			if err := definition.Decode(&b); err != nil {
				return fmt.Errorf("decoding wrapper input %q: %w", name, err)
			}
			if !reflect.DeepEqual(a, b) {
				return fmt.Errorf("existing input %q conflicts with the fullsend dispatch contract", name)
			}
			continue
		}
		inputs.Content = append(inputs.Content, scalarNode(name), definition)
	}
	if len(inputs.Content)/2 > 20 {
		return fmt.Errorf("combined GitLab pipeline contract declares %d inputs; maximum is 20; move user inputs to a separate included configuration", len(inputs.Content)/2)
	}
	return nil
}

func scalarNode(value string) *yaml.Node {
	return &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: value}
}

func addRootInputForwarding(root *yaml.Node) {
	include := findMappingValue(root, "include")
	if include == nil {
		return
	}
	items := include.Content
	if include.Kind != yaml.SequenceNode {
		items = []*yaml.Node{include}
	}
	for _, item := range items {
		if !isFullsendPipelineInclude(item) {
			continue
		}
		if item.Kind == yaml.ScalarNode {
			*item = *makeIncludeEntry(fullsendPipelineInclude)
		}
		for i := 0; i+1 < len(item.Content); i += 2 {
			if item.Content[i].Value == "inputs" {
				item.Content[i+1] = makeGitLabInputForwarding()
				return
			}
		}
		item.Content = append(item.Content,
			&yaml.Node{Kind: yaml.ScalarNode, Value: "inputs", Tag: "!!str"},
			makeGitLabInputForwarding())
		return
	}
}

func makeGitLabInputForwarding() *yaml.Node {
	n := &yaml.Node{Kind: yaml.MappingNode, Tag: "!!map"}
	for _, name := range gitlabDispatchInputNames {
		n.Content = append(n.Content,
			&yaml.Node{Kind: yaml.ScalarNode, Value: name, Tag: "!!str"},
			&yaml.Node{Kind: yaml.ScalarNode, Value: "$[[ inputs." + name + " ]]", Tag: "!!str"})
	}
	return n
}

// UnmergeGitLabCI removes fullsend's CI configuration from a
// .gitlab-ci.yml. It removes the fullsend pipeline include entry and
// the fullsend workflow:rules entries. Returns the cleaned YAML, or nil
// if the file has no remaining meaningful content.
func UnmergeGitLabCI(existing []byte) ([]byte, error) {
	if len(bytes.TrimSpace(existing)) == 0 {
		return nil, nil
	}

	docs, err := decodeGitLabDocuments(existing)
	if err != nil {
		return nil, fmt.Errorf("parsing .gitlab-ci.yml: %w", err)
	}
	if len(docs) == 0 {
		return nil, nil
	}
	doc := docs[len(docs)-1]

	if doc.Kind != yaml.DocumentNode || len(doc.Content) == 0 {
		return nil, nil
	}

	root := doc.Content[0]
	if root.Kind != yaml.MappingNode {
		return nil, nil
	}

	// Snapshot whether any non-fullsend include survives before
	// removeInclude strips fullsend's own entry, so the STAGE bridge
	// check below can tell a user-owned include apart from one this
	// unmerge is about to delete.
	survivingIncludes := gitlabRootHasOtherIncludes(root)
	removeInclude(root)
	removeStages(root)
	removeWorkflowRules(root)
	if variables := findMappingValue(root, "variables"); variables != nil && variables.Kind == yaml.MappingNode {
		if stage := findMappingValue(variables, "STAGE"); stage != nil && stage.Value == "$[[ inputs.stage ]]" &&
			!yamlReferencesVariable(root, "STAGE") && !yamlReferencesVariable(docs[0], "STAGE") &&
			!survivingIncludes && !yamlSubtreeHasSurvivingAlias(root, stage) {
			removeMappingKey(variables, "STAGE")
		}
		if len(variables.Content) == 0 {
			removeMappingKey(root, "variables")
		}
	}
	if len(docs) == 2 {
		header := docs[0].Content[0]
		// Only remove definitions matching our schema. A user-owned input
		// with a managed name but a different contract is not ours to delete.
		wrapper, loadErr := scaffold.GitLabPerRepoFile(fullsendPipelineInclude)
		if loadErr != nil {
			return nil, fmt.Errorf("loading GitLab input contract for cleanup: %w", loadErr)
		}
		contractDocs, decodeErr := decodeGitLabDocuments(wrapper)
		if decodeErr != nil {
			return nil, fmt.Errorf("decoding GitLab input contract for cleanup: %w", decodeErr)
		}
		managedInputs := findMappingValue(findMappingValue(contractDocs[0].Content[0], "spec"), "inputs")
		if spec := findMappingValue(header, "spec"); spec != nil && spec.Kind == yaml.MappingNode {
			if inputs := findMappingValue(spec, "inputs"); inputs != nil && inputs.Kind == yaml.MappingNode {
				for _, name := range gitlabDispatchInputNames {
					input := findMappingValue(inputs, name)
					if input == nil {
						continue
					}
					if yamlReferencesInput(root, name) || yamlReferencesInput(header, name) ||
						yamlSubtreeHasSurvivingAlias(header, input) {
						continue
					}
					var actual, managed any
					if input.Decode(&actual) == nil && findMappingValue(managedInputs, name).Decode(&managed) == nil && reflect.DeepEqual(actual, managed) {
						removeMappingKey(inputs, name)
					}
				}
				if len(inputs.Content) == 0 {
					removeMappingKey(spec, "inputs")
				}
			}
			if len(spec.Content) == 0 {
				removeMappingKey(header, "spec")
			}
		}
		if len(header.Content) == 0 {
			docs = docs[1:]
		}
	}

	// If the root mapping is empty after cleanup, the file has no
	// remaining content and should be deleted entirely.
	if len(root.Content) == 0 && len(docs) == 1 {
		return nil, nil
	}

	return renderGitLabDocuments(existing, docs)
}

// yamlSubtreeHasSurvivingAlias reports whether any alias node in doc, outside
// the subtree rooted at target, points at a node inside that subtree. Removing
// such a subtree would drop the anchor and leave the alias unresolvable, so
// the caller must preserve it.
func yamlSubtreeHasSurvivingAlias(doc, target *yaml.Node) bool {
	if doc == nil || target == nil {
		return false
	}
	inside := map[*yaml.Node]bool{}
	var collect func(*yaml.Node)
	collect = func(n *yaml.Node) {
		inside[n] = true
		for _, child := range n.Content {
			collect(child)
		}
	}
	collect(target)

	var visit func(*yaml.Node) bool
	visit = func(n *yaml.Node) bool {
		if inside[n] {
			return false
		}
		if n.Kind == yaml.AliasNode && inside[n.Alias] {
			return true
		}
		for _, child := range n.Content {
			if visit(child) {
				return true
			}
		}
		return false
	}
	return visit(doc)
}

func removeMappingKey(mapping *yaml.Node, key string) {
	if i := findMappingKeyIndex(mapping, key); i >= 0 {
		mapping.Content = append(mapping.Content[:i], mapping.Content[i+2:]...)
	}
}

func yamlReferencesInput(node *yaml.Node, name string) bool {
	pattern := regexp.MustCompile(`\$\[\[\s*inputs\.` + regexp.QuoteMeta(name) + `(?:\s|\||\])`)
	var visit func(*yaml.Node) bool
	visit = func(current *yaml.Node) bool {
		if pattern.MatchString(current.Value) {
			return true
		}
		for _, child := range current.Content {
			if visit(child) {
				return true
			}
		}
		return false
	}
	return visit(node)
}

// yamlReferencesVariable conservatively preserves bridges used indirectly by
// user scripts, rules, or settings, including shell parameter expansion.
func yamlReferencesVariable(node *yaml.Node, name string) bool {
	pattern := regexp.MustCompile(`\$(?:` + regexp.QuoteMeta(name) + `\b|\{` + regexp.QuoteMeta(name) + `(?:\}|[^A-Za-z0-9_]))`)
	var visit func(*yaml.Node) bool
	visit = func(current *yaml.Node) bool {
		if pattern.MatchString(current.Value) {
			return true
		}
		for _, child := range current.Content {
			if visit(child) {
				return true
			}
		}
		return false
	}
	return visit(node)
}

