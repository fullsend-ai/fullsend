// are no longer part of the current contract. Uninstall still removes
// them from a workflow block fullsend owns (see removeWorkflowRules);
// converge no longer migrates them.
var obsoleteGitLabWorkflowRules = []workflowRule{
	{If: `$CI_PIPELINE_SOURCE == "merge_request_event"`},
}

// gitlabCIWorkflowIsFullsendOwned reports whether a workflow: block shows
// positive evidence that fullsend, rather than the repo owner, installed
// it: the workflow carries the fullsend-generated name (set by
// newGitLabCI on fresh installs).
//
// Co-presence of fullsend's current schedule/api rules is deliberately
// NOT treated as a signal. mergeWorkflowRules appends fullsend's rules
// into ANY pre-existing workflow block unconditionally, regardless of
// what other rules that block already has, and never sets workflow.name
// (see newGitLabCI's doc comment). So a repo that independently
// configured its own merge_request_event gate and then enrolled fullsend
// via the merge path ends up with a rules set that "matches" fullsend's
// current required rules purely by coincidence of the merge having run —
// that only proves fullsend added *some* rules to this block, not that
// it added any particular other rule found alongside them. Absent the
// name signal, the block cannot be distinguished from one the repo owner
// configured independently.
func gitlabCIWorkflowIsFullsendOwned(workflow *yaml.Node) bool {
	nameVal := findMappingValue(workflow, "name")
	return nameVal != nil && strings.HasPrefix(nameVal.Value, fullsendWorkflowNamePrefix)
}

// MergeMissingGitLabDebugTraceRule adds fullsend's CI_DEBUG_TRACE
// deny-before-admit workflow rule (ADR 0125) to an existing .gitlab-ci.yml
// when it is missing, leaving everything else — including any
// already-present fullsend rules, the workflow name, auto_cancel
// settings, and any user configuration — untouched.
//
// This backfills already-enrolled repos: MergeGitLabCI (and the debug-trace
// rule it adds via fullsendWorkflowRules) only runs on fresh installs — the
// install call site skips it once HasFullsendEntries is true — and the
// periodic converge/upgrade path does not otherwise touch workflow:rules.
// Without this, a repo enrolled before this rule existed would never pick
// it up, leaving a debug-trace pipeline able to reach an admit rule and
// dump secrets at job init.
//
// The rule is only merged when gitlabCIWorkflowIsFullsendOwned finds
// positive evidence that fullsend, not the repo owner, installed the
// workflow block, so a user's own hand-written workflow: block is never
// modified.
//
// Returns the original content and changed=false when there is nothing to
// merge (no workflow: block, the rule is already present, or fullsend
// ownership of the block can't be established).
func MergeMissingGitLabDebugTraceRule(existing []byte) (result []byte, changed bool, err error) {
	if len(bytes.TrimSpace(existing)) == 0 {
		return existing, false, nil
	}

	docs, err := decodeGitLabDocuments(existing)
	if err != nil {
		return nil, false, fmt.Errorf("parsing .gitlab-ci.yml: %w", err)
	}
	if len(docs) == 0 {
		return existing, false, nil
	}
	doc := docs[len(docs)-1]
	if doc.Kind != yaml.DocumentNode || len(doc.Content) == 0 {
		return existing, false, nil
	}

	root := doc.Content[0]
	if root.Kind != yaml.MappingNode {
		return existing, false, nil
	}

	workflowVal := findMappingValue(root, "workflow")
	if workflowVal == nil || workflowVal.Kind != yaml.MappingNode {
		return existing, false, nil
	}

	// Only touch a workflow: block fullsend can prove it owns.
	if !gitlabCIWorkflowIsFullsendOwned(workflowVal) {
		return existing, false, nil
	}

	rulesVal := findMappingValue(workflowVal, "rules")
	if rulesVal != nil && rulesVal.Kind == yaml.SequenceNode && debugTraceDenyRuleSatisfied(rulesVal.Content) {
		return existing, false, nil
	}

	mergeWorkflowRules(workflowVal)

	out, marshalErr := renderGitLabDocuments(existing, docs)
	if marshalErr != nil {
		return nil, false, marshalErr
	}
	return out, true, nil
}

// hasInterpolationSyntax reports whether a key or value's literal text
// carries GitLab pipeline-input interpolation syntax (`$[[ ... ]]`) or
// CI/CD variable-expansion syntax (`${...}`). A name containing either
// can't be trusted as a stable literal: it may evaluate to a different
// name entirely at pipeline time (e.g. a top-level key that resolves to
// "include" or "stages", or an ordinary-looking key that resolves to
// "stage"/"<<"/"extends"), so callers that need a proven identity — as
// opposed to classifyTopLevelKey's plain job-name classification, which
// intentionally keeps a literal, non-interpolated "$" in a job name
// scannable (e.g. "weird$job") — must fail closed on it instead of
// trusting the raw text.
func hasInterpolationSyntax(name string) bool {
	return strings.Contains(name, "$[[") || strings.Contains(name, "${")
}

// classifyTopLevelKey resolves a mapping key to a plain name usable for
// lookup and classification: an AliasNode is dereferenced first, and the
// result must be a plain, untagged ScalarNode. ok is false for anything
// else (an unresolvable/cyclic alias, a non-core-tagged key, or a
// non-scalar key) — such a key can't be classified as reserved
// configuration, a hidden template, or an ordinary job name, so callers
// must treat it conservatively (fail closed) rather than guess.
//
// This is the single source of truth for key classification shared by the
// trigger-admission and dispatcher-template scans, so they can't drift
// apart on what counts as a classifiable key.
func classifyTopLevelKey(keyNode *yaml.Node) (name string, ok bool) {
	resolved := keyNode
	if keyNode.Kind == yaml.AliasNode {
		resolved = resolveAlias(keyNode)
	}
	if resolved == nil || resolved.Kind != yaml.ScalarNode || hasNonCoreTag(resolved) {
		return "", false
	}
	return resolved.Value, true
}

// classifyTopLevelKeys walks every key/value pair in root once, resolving
// each key via classifyTopLevelKey, and collects every occurrence of each
// resolved name. ok is false — fail closed — when any top-level key can't
// be classified (an alias to something other than a plain untagged
// scalar, a non-core-tagged key, or a non-scalar key), since such a key
// might resolve to a name a caller needs to see (e.g. "include" or
// "stages") and would otherwise be silently invisible to it.
//
// Unlike the literal, first-match lookups findMappingValue and
// findMappingKeyIndex perform, a top-level key hidden behind an AliasNode,
// or a duplicate key that GitLab/Psych's last-wins semantics would apply,
// can't be silently collapsed to a single first-match occurrence.
//
// A key whose literal text carries interpolation syntax (`$[[ ... ]]` or
// `${...}`, see hasInterpolationSyntax) is also treated as unclassifiable
// here, even though classifyTopLevelKey itself resolved it to a plain
// scalar: e.g. a second top-level `$[[ inputs.extra ]]:` key could
// evaluate to a name a caller looks up at pipeline time, hiding a
// duplicate occurrence from it. This check is scoped to
// classifyTopLevelKeys rather than classifyTopLevelKey itself so an
// ordinary, non-interpolated `$`-bearing job name (e.g. "weird$job")
// remains scannable via the shared helper's other callers.
func classifyTopLevelKeys(root *yaml.Node) (keys map[string][]*yaml.Node, ok bool) {
	keys = make(map[string][]*yaml.Node, len(root.Content)/2)
	ok = true
	for i := 0; i+1 < len(root.Content); i += 2 {
		name, keyOk := classifyTopLevelKey(root.Content[i])
		if !keyOk || hasInterpolationSyntax(name) {
			ok = false
			continue
		}
		keys[name] = append(keys[name], root.Content[i+1])
	}
	return keys, ok
}

// hasNonCoreTag reports whether node carries a YAML tag other than one of
// the core tags the parser assigns during its own default resolution
// (e.g. "!!str", "!!seq", "!!map", or "" for an as-yet-unresolved node). A
// non-core tag — such as GitLab's `!reference` — means the node's shape
// can't be taken at face value: `!reference [.setup, scaling]` is a
// two-element reference path, not a sequence of two job/stage names, even
// though its Kind is yaml.SequenceNode like an ordinary list.
func hasNonCoreTag(node *yaml.Node) bool {
	switch node.Tag {
	case "", "!!str", "!!seq", "!!map", "!!null", "!!bool", "!!int", "!!float", "!!timestamp", "!!binary", "!!merge":
		return false
	default:
		return true
	}
}

// resolveAlias dereferences a chain of YAML alias nodes, returning the
// first non-alias node encountered, or nil if the chain is cyclic.
func resolveAlias(node *yaml.Node) *yaml.Node {
	seen := make(map[*yaml.Node]bool)
	for node != nil && node.Kind == yaml.AliasNode {
		if seen[node] {
			return nil
		}
		seen[node] = true
		node = node.Alias
	}
	return node
}

// isLiteralScalarValue resolves node to a literal, fully-determined scalar
// value suitable for equality comparison: aliases are dereferenced first,
// and the result must be a plain, untagged scalar. ok is false for
// anything else — an unresolvable/cyclic alias, a non-core-tagged value,
// or a non-scalar value — and also for a scalar whose text contains GitLab
// CI/CD variable or pipeline-input interpolation syntax ($VAR, ${VAR}, or
// $[[ ... ]]): such a value is the unevaluated expression text, not the
// value GitLab will actually substitute at pipeline time, so it can't be
// compared as a literal even though it's a plain, untagged ScalarNode.
//
// Centralizing this check means every site in this file that compares a
// resolved scalar for equality (a job's stage: value, an include mapping's
// local: value) shares one fail-closed definition of "known literal" —
// closing an unproven-scalar shape here closes it everywhere at once,
// instead of requiring a matching fix at each call site individually.
func isLiteralScalarValue(node *yaml.Node) (value string, ok bool) {
	resolved := resolveAlias(node)
	if resolved == nil || resolved.Kind != yaml.ScalarNode || hasNonCoreTag(resolved) {
		return "", false
	}
	if strings.Contains(resolved.Value, "$") {
		return "", false
	}
	return resolved.Value, true
}

// extendsNames returns the job/template names referenced by an extends:
// value, which GitLab allows as either a single scalar or a sequence, and
// reports whether the value's shape could be fully resolved. The value
// itself, and each item when it's a sequence, is resolved via
// isLiteralScalarValue rather than a bare resolveAlias/Kind check: that
// centralizes alias dereferencing, the non-core-tag guard (so GitLab's
// `extends: !reference [.setup, scaling]` — a SequenceNode shape identical
// to a two-name extends list, but a reference path rather than job/template
// names — is treated as unresolvable rather than parsed as one), and the
// GitLab CI/CD variable/pipeline-input interpolation guard ($VAR, ${VAR},
// $[[ ... ]]) shared with the stage:/include local: call sites. Without the
// interpolation guard, `extends: $[[ inputs.template ]]` would be treated
// as literally extending a template named "$[[ inputs.template ]]" — a
// name no job actually has — silently missing the real (possibly
// stage-carrying) target instead of failing closed. ok is false when the
// value, or any item within it, isn't a fully-literal scalar by that
// definition, meaning the effective extends target(s) couldn't be
// determined.
func extendsNames(node *yaml.Node) (names []string, ok bool) {
	if value, literalOK := isLiteralScalarValue(node); literalOK {
		return []string{value}, true
	}
	resolved := resolveAlias(node)
	if resolved == nil || hasNonCoreTag(resolved) || resolved.Kind != yaml.SequenceNode {
		return nil, false
	}
	names = make([]string, 0, len(resolved.Content))
	for _, item := range resolved.Content {
		value, itemOK := isLiteralScalarValue(item)
		if !itemOK {
			return nil, false
		}
		names = append(names, value)
	}
	return names, true
}

// HasFullsendEntries reports whether existing .gitlab-ci.yml content
// already contains all fullsend CI entries. It performs semantic drift
// detection by checking:
//
//  1. include: contains the fullsend-pipeline.yml entry
//  2. If stages: exists, it contains dispatch, poll, agent
//     (if no stages: key, the included pipeline provides them).
//  3. If workflow: exists, it must have a rules: sequence containing
//     fullsend's if: conditions. If workflow: exists without
//     rules:, that is drift — MergeGitLabCI would add them.
//     (if no workflow: block at all, fullsend's jobs self-filter)
//
// Used by the installer to skip unnecessary .gitlab-ci.yml writes when
// all entries are already present, avoiding YAML formatting churn.
func HasFullsendEntries(existing []byte) bool {
	if len(bytes.TrimSpace(existing)) == 0 {
		return false
	}

	docs, err := decodeGitLabDocuments(existing)
	if err != nil || len(docs) == 0 {
		return false
	}
	doc := docs[len(docs)-1]

	if doc.Kind != yaml.DocumentNode || len(doc.Content) == 0 {
		return false
	}

	root := doc.Content[0]
	if root.Kind != yaml.MappingNode {
		return false
	}

	// 1. The include: key must exist and contain fullsend-pipeline.yml.
	includeVal := findMappingValue(root, "include")
	if includeVal == nil {
		return false
	}
	if includeVal.Kind == yaml.SequenceNode {
		if !slices.ContainsFunc(includeVal.Content, isFullsendPipelineInclude) {
			return false
		}
	} else if !isFullsendPipelineInclude(includeVal) {
		return false
	}

	// 2. If stages: exists, it must contain all fullsend stages.
	stagesVal := findMappingValue(root, "stages")
	if stagesVal != nil && stagesVal.Kind == yaml.SequenceNode {
		existingStages := make(map[string]bool)
		for _, item := range stagesVal.Content {
			if item.Kind == yaml.ScalarNode {
				existingStages[item.Value] = true
			}
		}
		for _, stage := range fullsendStages {
			if !existingStages[stage] {
				return false
			}
		}
	}

	// 3. If workflow: exists, rules: must be present and contain
	//    fullsend's if: conditions. A workflow: block without rules:
	//    is drift — MergeGitLabCI would add them.
	workflowVal := findMappingValue(root, "workflow")
	if workflowVal != nil && workflowVal.Kind == yaml.MappingNode {
		rulesVal := findMappingValue(workflowVal, "rules")
		if rulesVal == nil || rulesVal.Kind != yaml.SequenceNode {
			// workflow: exists but has no rules: sequence —
			// MergeGitLabCI would add rules here.
			return false
		}
		existingRules := make(map[string]bool)
		for _, item := range rulesVal.Content {
			if item.Kind == yaml.MappingNode {
				if v := findMappingValue(item, "if"); v != nil {
					existingRules[v.Value] = true
				}
			}
		}
		for _, r := range fullsendWorkflowRules {
			if !existingRules[r.If] {
				return false
			}
		}
	}

	return true
}

// MergeGitLabCI merges fullsend's CI configuration into an existing
// .gitlab-ci.yml. It uses yaml.v3's Node API to preserve comments in the
// existing file, and renderGitLabDocuments to keep its blank lines and to
// return it byte-for-byte when nothing needs merging.
//
// The merge performs up to three operations:
//  1. Appends an include entry for .gitlab/ci/fullsend-pipeline.yml
//     (skipped if already present)
//  2. Appends fullsend's current stages (dispatch, poll, agent) to
//     the existing stages: array, deduplicating if already present.
//     Skipped when no stages: key exists.
//  3. When a workflow: block already exists, merges workflow:rules
//     entries (deduplicates by if: condition) and sets
//     auto_cancel.on_new_commit: none if not present. When no
//     workflow: block exists, it is left absent so the repo's
//     push-triggered pipelines are not disrupted.
//
// When existing is nil or empty, returns a minimal .gitlab-ci.yml with
// just the fullsend include and workflow block.
func MergeGitLabCI(existing []byte) ([]byte, error) {
	wrapper, err := scaffold.GitLabPerRepoFile(fullsendPipelineInclude)
	if err != nil {
		return nil, fmt.Errorf("loading GitLab wrapper: %w", err)
	}
	return mergeGitLabCIWithWrapper(existing, wrapper)
}

// mergeGitLabCIWithWrapper uses the effective wrapper's schema, including
// remote pinned templates. The wrapper must declare the typed pipeline-input
// contract; a legacy variable-based wrapper is rejected (see
// legacyGitLabWrapperError).
func mergeGitLabCIWithWrapper(existing, wrapper []byte) ([]byte, error) {
	if len(bytes.TrimSpace(existing)) == 0 {
		existing = []byte("include: []\nworkflow:\n  name: 'fullsend $CI_PIPELINE_SOURCE'\n")
	}
	// source is the content whose formatting the merged output keeps
	// (see renderGitLabDocuments); it tracks the placeholder below when
	// the existing file has no documents to merge into.
	source := existing

	docs, err := decodeGitLabDocuments(existing)
	if err != nil {
		return nil, fmt.Errorf("parsing existing .gitlab-ci.yml: %w", err)
	}
	if len(docs) == 0 {
		// A comments-only (or otherwise entirely empty) existing file
		// decodes to zero non-empty documents. Normalize it to the same
		// minimal placeholder body used for a genuinely empty file above
		// and continue merging with the supplied wrapper, rather than
		// discarding that wrapper for newGitLabCI's embedded default, so
		// the merged root always matches the wrapper being delivered.
		source = []byte("include: []\nworkflow:\n  name: 'fullsend $CI_PIPELINE_SOURCE'\n")
		docs, err = decodeGitLabDocuments(source)
		if err != nil {
			return nil, fmt.Errorf("parsing placeholder .gitlab-ci.yml: %w", err)
		}
	}
	rootDoc := docs[len(docs)-1]
	if rootDoc.Kind != yaml.DocumentNode || len(rootDoc.Content) == 0 {
		return newGitLabCI()
	}
	root := rootDoc.Content[0]
	if root.Kind != yaml.MappingNode {
		return nil, fmt.Errorf(".gitlab-ci.yml pipeline body must be a mapping")
	}
	contractDocs, err := decodeGitLabDocuments(wrapper)
	if err != nil {
		return nil, fmt.Errorf("parsing GitLab wrapper: %w", err)
	}
	if !gitlabWrapperHasDispatchInputs(wrapper) {
		// Only the typed pipeline-input contract is supported; an
		// incomplete contract or a legacy variable-based wrapper is
		// rejected rather than merged.
		if err := requireCompleteGitLabDispatchContract(wrapper); err != nil {
			return nil, err
		}
		return nil, legacyGitLabWrapperError()
	}
	contract := contractDocs[0].Content[0]
	if docs, err = mergeGitLabInputContract(docs, contract); err != nil {
		return nil, err
	}
	if len(docs) > 2 {
		return nil, fmt.Errorf(".gitlab-ci.yml must contain a spec header and one pipeline body")
	}
	if err := mergeInclude(root); err != nil {
		return nil, err
	}
	addRootInputForwarding(root)
	variables := findMappingValue(root, "variables")
	if variables == nil {
		variables = &yaml.Node{Kind: yaml.MappingNode, Tag: "!!map"}
		root.Content = append(root.Content, scalarNode("variables"), variables)
	}
	if variables.Kind != yaml.MappingNode {
		return nil, fmt.Errorf("variables: is not a mapping")
	}
	stage := findMappingValue(variables, "STAGE")
	if stage == nil {
		variables.Content = append(variables.Content, scalarNode("STAGE"), scalarNode("$[[ inputs.stage ]]"))
	} else if !gitlabVariableBridgesInput(variables, "STAGE", "stage") {
		// gitlabVariableBridgesInput accepts both GitLab's plain-scalar
		// variable syntax and its extended ({value:, expand:}) form, so
		// a compatible extended declaration such as
		// STAGE: {value: '$[[ inputs.stage ]]', expand: false} is
		// preserved here rather than rejected — comparing stage.Value
		// directly would see an empty scalar on a mapping node and
		// report a spurious conflict. See the review finding on this
		// comparison.
		return nil, fmt.Errorf("existing STAGE variable conflicts with the dispatch input bridge")
	}
	mergeStages(root)
	if err := mergeWorkflow(root); err != nil {
		return nil, err
	}

	return renderGitLabDocuments(source, docs)
}

func decodeGitLabDocuments(content []byte) ([]*yaml.Node, error) {
	decoder := yaml.NewDecoder(bytes.NewReader(content))
	var docs []*yaml.Node
	for {
		var doc yaml.Node
		if err := decoder.Decode(&doc); err != nil {
			if err == io.EOF {
				return docs, nil
			}
			return nil, err
		}
		if len(doc.Content) != 0 {
			docs = append(docs, &doc)
		}
	}
}

func gitlabWrapperHasDispatchInputs(content []byte) bool {
	docs, err := decodeGitLabDocuments(content)
	if err != nil || len(docs) != 2 {
		return false
	}
	spec := findMappingValue(docs[0].Content[0], "spec")
	if spec == nil || spec.Kind != yaml.MappingNode {
		return false
	}
	inputs := findMappingValue(spec, "inputs")
	if inputs == nil || inputs.Kind != yaml.MappingNode {
		return false
	}
	for _, name := range gitlabDispatchInputNames {
		if findMappingValue(inputs, name) == nil {
			return false
		}
	}
	return true
}

// gitlabWrapperDeclaresSpecInputs reports whether content declares a
// spec:inputs mapping at all, regardless of whether it carries the full
// dispatch contract gitlabWrapperHasDispatchInputs requires.
func gitlabWrapperDeclaresSpecInputs(content []byte) bool {
	docs, err := decodeGitLabDocuments(content)
	if err != nil || len(docs) != 2 {
		return false
	}
	spec := findMappingValue(docs[0].Content[0], "spec")
	if spec == nil || spec.Kind != yaml.MappingNode {
		return false
	}
	inputs := findMappingValue(spec, "inputs")
	return inputs != nil && inputs.Kind == yaml.MappingNode
}

// gitlabWrapperHasPartialDispatchInputs reports whether content declares a
// spec:inputs mapping that attempts the pipeline-input dispatch contract
// but is missing one or more of the required names. gitlabWrapperHasDispatchInputs
// classifies such a wrapper as "not typed", the same verdict it gives a
// legacy, variable-based wrapper; requireCompleteGitLabDispatchContract
// uses this to report the incomplete contract specifically rather than
// describing it as a legacy wrapper.
func gitlabWrapperHasPartialDispatchInputs(content []byte) bool {
	return gitlabWrapperDeclaresSpecInputs(content) && !gitlabWrapperHasDispatchInputs(content)
}

// errGitLabIncompatibleWrapper marks a wrapper whose transport contract is
// incompatible (an incomplete typed contract, a typed contract lacking
// the literal-scheduled marker, or a legacy variable-based wrapper). Callers that inspect the *installed*
// wrapper can use errors.Is to tell this content problem — which a scaffold
// repair resolves — apart from an API/read failure.
var errGitLabIncompatibleWrapper = errors.New("incompatible GitLab wrapper contract")

// requireCompleteGitLabDispatchContract rejects a wrapper that declares an
// incomplete spec:inputs pipeline-input contract, which is not a valid
// typed one. See gitlabWrapperHasPartialDispatchInputs and the fail-open
// review finding on typed-transport detection.
func requireCompleteGitLabDispatchContract(content []byte) error {
	if gitlabWrapperHasPartialDispatchInputs(content) {
		return fmt.Errorf("%w: GitLab wrapper declares an incomplete spec:inputs pipeline-input dispatch contract (missing one or more of the %d required inputs); this is not a valid typed contract and must not be delivered or activated", errGitLabIncompatibleWrapper, len(gitlabDispatchInputNames))
	}
	return nil
}

// gitlabFirstTypedDispatchRelease is the first fullsend release whose GitLab
// scaffold carries the typed pipeline-input dispatch contract. Older pinned
// scaffolds deliver the legacy variable-based wrapper, which is no longer
// supported.
const gitlabFirstTypedDispatchRelease = "v0.46.0"

// errGitLabLegacyWrapper marks a wrapper on the former variable-based
// dispatch contract. It wraps errGitLabIncompatibleWrapper, so callers that
// defer on any incompatible wrapper also defer on a legacy one.
var errGitLabLegacyWrapper = fmt.Errorf("%w: %s uses the legacy pipeline-variable dispatch contract, which is no longer supported", errGitLabIncompatibleWrapper, fullsendPipelineInclude)

// legacyGitLabWrapperError reports a wrapper on the former variable-based
// dispatch contract. The automatic migration away from that contract has
// been removed, so such a wrapper is incompatible rather than handled.
func legacyGitLabWrapperError() error {
	return fmt.Errorf("%w; pin fullsend_ref to %s or later (or remove the pin) so the typed pipeline-input wrapper is delivered", errGitLabLegacyWrapper, gitlabFirstTypedDispatchRelease)
}

// requireTypedGitLabWrapper accepts only a wrapper on the complete typed
// pipeline-input contract. An incomplete contract or a legacy
// variable-based wrapper is rejected with errGitLabIncompatibleWrapper.
func requireTypedGitLabWrapper(content []byte) error {
	if gitlabWrapperHasDispatchInputs(content) {
		return validateGitLabTypedContract(content)
	}
	if err := requireCompleteGitLabDispatchContract(content); err != nil {
		return err
	}
	return legacyGitLabWrapperError()
}

func effectiveGitLabWrapper(ctx context.Context, client forge.Client, owner, repo string, pending []forge.TreeFile) ([]byte, error) {
	for _, file := range pending {
		if file.Path == fullsendPipelineInclude {
			return file.Content, nil
		}
	}
	content, err := client.GetFileContent(ctx, owner, repo, fullsendPipelineInclude)
	if forge.IsNotFound(err) {
		return nil, nil
	}
	return content, err
}

// GitLabUsesTypedDispatch reports whether a wrapper is installed on the
// default branch: it returns false with no error when none is committed yet.
// A pending fresh install is gated separately against its queued scaffold.
// An installed wrapper must carry the complete typed pipeline-input
// contract; an incomplete contract or a legacy variable-based wrapper is
// rejected with errGitLabIncompatibleWrapper — see requireTypedGitLabWrapper.
func GitLabUsesTypedDispatch(ctx context.Context, client forge.Client, owner, repo string) (bool, error) {
	content, err := effectiveGitLabWrapper(ctx, client, owner, repo, nil)
	if err != nil {
		return false, err
	}
	if content == nil {
		return false, nil
	}
	if err := requireTypedGitLabWrapper(content); err != nil {
		return false, err
	}
	return true, nil
}

// gitlabRootDeclaresDispatchInputs reports whether the committed root
// .gitlab-ci.yml both declares the full pipeline-input contract in its own
// spec:inputs header and forwards every one of those inputs to the
// fullsend pipeline include. GitLabUsesTypedDispatch only observes the
// wrapper (fullsendPipelineInclude); a wrapper that already landed as
// typed does not guarantee the sibling root migration committed too — an
// unmerged root-repair MR can leave the root's include:inputs forwarding
// map (or its spec:inputs header) stale or absent while the wrapper is
// typed. ActivateGitLabTypedDispatch must not enforce the restriction
// against that incompatible root — see the review finding
// on activation's incomplete guard.
func gitlabRootDeclaresDispatchInputs(ctx context.Context, client forge.Client, owner, repo string) (bool, error) {
	content, err := client.GetFileContent(ctx, owner, repo, ".gitlab-ci.yml")
	if forge.IsNotFound(err) {
		return false, nil
	}
	if err != nil {
		return false, err
	}
	if !gitlabWrapperHasDispatchInputs(content) {
		return false, nil
	}
	docs, err := decodeGitLabDocuments(content)
	if err != nil || len(docs) != 2 {
		return false, nil
	}
	root := docs[1].Content[0]
	if root.Kind != yaml.MappingNode {
		return false, nil
	}
	include := findMappingValue(root, "include")
	if include == nil {
		return false, nil
	}
	items := include.Content
	if include.Kind != yaml.SequenceNode {
		items = []*yaml.Node{include}
	}
	for _, item := range items {
		if !isFullsendPipelineInclude(item) || item.Kind != yaml.MappingNode {
			continue
		}
		inputs := findMappingValue(item, "inputs")
		if inputs == nil || inputs.Kind != yaml.MappingNode {
			return false, nil
		}
		for _, name := range gitlabDispatchInputNames {
			value := findMappingValue(inputs, name)
			// A present key is not enough: it must actually forward the
			// root's own matching input (addRootInputForwarding's
			// "$[[ inputs.<name> ]]" form), not a stale or blank value
			// left behind by an unmerged repair MR — see the review
			// finding on this guard's incomplete value check.
			if value == nil || value.Kind != yaml.ScalarNode || value.Value != "$[[ inputs."+name+" ]]" {
				return false, nil
			}
		}
		return true, nil
	}
	return false, nil
}

