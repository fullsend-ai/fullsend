// managedConfigMarker is the ADR-0122 ownership marker every managed
// .fullsend/config.yaml write on the install path (desiredManagedConfig)
// prefixes to its canonical bytes, verbatim as specified in ADR-0122's
// "Decision" section. Its presence is what distinguishes a file this
// package owns from a hand-authored one: convergeManagedConfigFiles and
// checkManagedConfigDrift in managed_config_lifecycle.go refuse to treat
// an existing markerless file as ordinary drift, since the manifest may
// not restate every restriction (kill_switch, roles,
// allowed_remote_resources, ...) the hand-authored file set, and silently
// overwriting it would drop them.
const managedConfigMarker = "# This file is managed by 'fullsend repos': repos-config-v1\n" +
	"# Do not edit this file directly; changes will be overwritten.\n"

// managedConfigSourcePrefix introduces the optional line, written directly
// after managedConfigMarker, that names the repos.yaml manifest the file was
// rendered from (#8627). The marker itself is unchanged, so
// hasManagedConfigMarker's prefix match still recognizes the file, and a
// file without this line never requires adoption. The line is informational:
// drift and convergence ignore it (managedConfigEquivalent, #8785).
const managedConfigSourcePrefix = "# Source manifest: "

// sanitizeManifestSource returns the location of an HTTPS manifest in a form
// safe to publish in the target repository, or "" when it is not known to be
// safe. The line lands in the target repository's Git history, which may be
// public, and a manifest URL can carry a credential anywhere (userinfo,
// query, fragment, or a path segment such as https://host/t/<token>/repos.yaml).
// No shape heuristic can tell a short or hex-looking token from a directory
// name, so the source is recorded only for recognized source-hosting URL
// structures whose path is repository coordinates rather than an opaque
// credential slot (see recognizedManifestSourcePath); every other URL, and
// anything that is not an absolute HTTPS URL without a port, is omitted.
// Within a recognized structure only scheme, host and path are kept
// (userinfo, query and fragment are dropped), and every path segment must be
// plain: only characters from [A-Za-z0-9._~-], which excludes path
// parameters, percent-escapes and control characters that could break out of
// the YAML comment. The dot segments "." and ".." are rejected too: the path
// is written unnormalized, so they could otherwise resolve outside the
// recognized raw-file route.
func sanitizeManifestSource(raw string) string {
	u, err := url.Parse(raw)
	if err != nil || !strings.EqualFold(u.Scheme, "https") || u.Port() != "" {
		return ""
	}
	host := strings.ToLower(u.Hostname())
	segs := strings.Split(strings.TrimPrefix(u.EscapedPath(), "/"), "/")
	for _, seg := range segs {
		if seg == "" || seg == "." || seg == ".." || !plainPathSegment(seg) {
			return ""
		}
	}
	if !recognizedManifestSourcePath(host, segs) {
		return ""
	}
	return (&url.URL{Scheme: "https", Host: host, Path: u.Path}).String()
}

// recognizedManifestSourcePath reports whether segs (the non-empty path
// segments of an HTTPS URL on host) match a known raw-file URL structure of
// a public source host, whose segments are owner, repository, ref and file
// path:
//
//	raw.githubusercontent.com/<owner>/<repo>/<ref>/<path...>
//	github.com/<owner>/<repo>/raw/<ref>/<path...>
//	gitlab.com/<group...>/<project>/-/raw/<ref>/<path...>
func recognizedManifestSourcePath(host string, segs []string) bool {
	switch host {
	case "raw.githubusercontent.com":
		return len(segs) >= 4
	case "github.com":
		return len(segs) >= 5 && segs[2] == "raw"
	case "gitlab.com":
		for i := 1; i+3 < len(segs); i++ {
			if segs[i] == "-" && segs[i+1] == "raw" {
				return true
			}
		}
	}
	return false
}

// plainPathSegment reports whether seg consists only of unreserved URL
// characters.
func plainPathSegment(seg string) bool {
	for _, r := range seg {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r >= '0' && r <= '9':
		case r == '.', r == '_', r == '~', r == '-':
		default:
			return false
		}
	}
	return true
}

// managedConfigHeader returns the comment header every managed
// .fullsend/config.yaml begins with: the ADR-0122 ownership marker, followed
// by a line naming the originating manifest when source is a sanitizable
// HTTPS URL.
func managedConfigHeader(source string) string {
	source = sanitizeManifestSource(source)
	if source == "" {
		return managedConfigMarker
	}
	return managedConfigMarker + managedConfigSourcePrefix + source + "\n"
}

// hasManagedConfigMarker reports whether content already begins with the
// ADR-0122 ownership marker written by desiredManagedConfig. A file
// lacking the marker predates managed-configuration adoption (or was
// edited by hand) and must not be silently rewritten as ordinary drift.
func hasManagedConfigMarker(content []byte) bool {
	return bytes.HasPrefix(content, []byte(managedConfigMarker))
}

// stripManagedConfigSource returns content without the optional
// source-manifest line that directly follows the ownership marker. The line
// is stripped only when it is exactly what managedConfigHeader writes: the
// prefix, a URL that sanitizeManifestSource leaves unchanged (so it holds no
// CR, NEL, LS, PS or other character the YAML parser would treat as a line
// break), and a terminating LF. Anything else, including content without the
// marker or with no source line, is returned unchanged so it is compared in
// full; otherwise a new slice is returned and content is not modified.
func stripManagedConfigSource(content []byte) []byte {
	if !hasManagedConfigMarker(content) {
		return content
	}
	rest := content[len(managedConfigMarker):]
	if !bytes.HasPrefix(rest, []byte(managedConfigSourcePrefix)) {
		return content
	}
	line, body, found := bytes.Cut(rest[len(managedConfigSourcePrefix):], []byte("\n"))
	if !found {
		return content
	}
	if src := string(line); src == "" || sanitizeManifestSource(src) != src {
		return content
	}
	out := make([]byte, 0, len(content))
	out = append(out, managedConfigMarker...)
	return append(out, body...)
}

// managedConfigEquivalent reports whether an installed managed
// .fullsend/config.yaml matches the desired rendered bytes, ignoring the
// informational source-manifest line (#8785). That line records only where
// the manifest was loaded from, so the same manifest addressed by a local
// path (no line) or by an HTTPS URL (a line) must not count as drift or
// make convergence rewrite the file back and forth. Everything else,
// including the ownership marker and the configuration body, is compared
// byte for byte.
func managedConfigEquivalent(existing, desired []byte) bool {
	return bytes.Equal(stripManagedConfigSource(existing), stripManagedConfigSource(desired))
}

// readExistingFile reads path on the default branch and reports whether
// the file exists. A zero-byte file exists: it returns found with empty,
// non-nil content so callers do not mistake it for an absent file. Read
// errors other than not-found are returned unwrapped.
func readExistingFile(ctx context.Context, client forge.Client, owner, repo, path string) (data []byte, found bool, err error) {
	data, err = client.GetFileContent(ctx, owner, repo, path)
	if err != nil {
		if forge.IsNotFound(err) {
			return nil, false, nil
		}
		return nil, false, err
	}
	if data == nil {
		data = []byte{}
	}
	return data, true, nil
}

// overlayNeedsAdoption reports whether an existing .fullsend/config.yaml
// requires adoption: any existing file, including a zero-byte one, that
// lacks the ownership marker.
func overlayNeedsAdoption(found bool, content []byte) bool {
	return found && !hasManagedConfigMarker(content)
}

// mergeManagedConfig flattens defaults.config, the forge section's config
// (platform, which may be nil), and the repository config, in that order,
// into a sparse managed configuration using the per-field merge rules of
// per-repo config. It does not bake in code defaults or config.base.yaml.
func (m *Manifest) mergeManagedConfig(platform *PlatformConfig, entry RepoEntry) config.PerRepoConfigWriter {
	var platformLayer config.PerRepoConfigWriter
	if platform != nil {
		platformLayer = platform.Config.Writer()
	}
	merged := config.MergeManaged(config.MergeManaged(m.Defaults.Config.Writer(), platformLayer), entry.Config.Writer())
	if merged == nil {
		merged = config.NewEmptyPerRepoOverlay()
	}
	return merged
}

// RenderManagedConfig returns the canonical sparse configuration YAML body
// for a repository — the explicitly supplied manifest values, with no code
// defaults or config.base.yaml baked in. Every manifest repository is
// managed (#8218), so ok is always true; an omitted config renders only
// the values the manifest declares, so omitted values still inherit from
// presets and code defaults.
//
// The returned bytes deliberately carry no file header. perRepoConfig's
// Marshal() prepends perRepoConfigHeader, the unmanaged per-repo-install
// header — not the ADR 0122 ownership marker
// ("# This file is managed by 'fullsend repos': ...") that every managed
// .fullsend/config.yaml written by the install path begins with. This
// function has no adoption-detection state (no forge read of the existing
// file), so it cannot decide whether the marker belongs on the result or
// whether an existing file requires adoption first; it renders the config
// body only. desiredManagedConfig is the install-path renderer (#7632)
// that prefixes the marker and is compared against the installed file by
// convergeManagedConfigFiles / checkManagedConfigDrift in
// managed_config_lifecycle.go, which also implement the adoption gate for
// an existing markerless file.
//
// forgeName selects the forge section (github or gitlab) whose config
// layer applies to entry.
func (m *Manifest) RenderManagedConfig(forgeName string, entry RepoEntry) (data []byte, ok bool, err error) {
	body, err := marshalManagedConfig(m.mergeManagedConfig(m.PlatformFor(forgeName), entry))
	if err != nil {
		return nil, true, err
	}
	return body, true, nil
}

// desiredManagedConfig returns the canonical managed-configuration bytes
// for a config-managed repository, prefixed with the ADR-0122 ownership
// marker (managedConfigMarker) and, for a manifest loaded from an HTTPS URL,
// a line naming that manifest (managedConfigHeader). ok is false when the
// repository is not config-managed. This is the install path's renderer: install, converge,
// and status all compare the installed .fullsend/config.yaml against these
// bytes, so the marker is part of both the write and the whole-file
// compare; only the source-manifest line is ignored by that compare
// (managedConfigEquivalent).
func desiredManagedConfig(resolved ResolvedConfig) (data []byte, ok bool, err error) {
	if !resolved.ConfigManaged {
		return nil, false, nil
	}
	body, err := marshalManagedConfig(resolved.Managed)
	if err != nil {
		return nil, true, err
	}
	return append([]byte(managedConfigHeader(resolved.ManifestSource)), body...), true, nil
}

// marshalManagedConfig does not prefix its own errors with "managed
// config" — every caller already wraps the returned error with its own
// "rendering managed config..." context, and adding the same phrase here
// would stutter it.
func marshalManagedConfig(cfg config.PerRepoConfigWriter) ([]byte, error) {
	if cfg == nil {
		cfg = config.NewEmptyPerRepoOverlay()
	}
	if err := config.ValidateMergedManaged(cfg); err != nil {
		return nil, err
	}
	if err := validateManagedMintAndWIF(cfg); err != nil {
		return nil, err
	}
	if err := ValidateAllowedRemoteResourcesFormat("allowed_remote_resources", cfg.AllowedResources()); err != nil {
		return nil, err
	}
	body, err := yaml.Marshal(cfg)
	if err != nil {
		return nil, fmt.Errorf("marshaling: %w", err)
	}
	return body, nil
}

// LayeredConfig returns the effective per-repo configuration for entry in
// the forgeName section: managed configuration (repository config →
// forge section config → defaults.config) → config.base.yaml (baseYAML) →
// code defaults. baseYAML may be empty.
func (m *Manifest) LayeredConfig(forgeName string, entry RepoEntry, baseYAML []byte) (config.PerRepoConfigReader, error) {
	return config.LayerOnBase(m.mergeManagedConfig(m.PlatformFor(forgeName), entry), baseYAML)
}

func validateManifestManaged(m *Manifest) error {
	if err := validateManagedBlock("defaults.config", m.Defaults.Config); err != nil {
		return err
	}
	for _, p := range []struct {
		name string
		cfg  *PlatformConfig
	}{{ForgeGitHub, m.GitHub}, {ForgeGitLab, m.GitLab}} {
		if p.cfg == nil {
			continue
		}
		if err := validateManagedBlock(p.name+".config", p.cfg.Config); err != nil {
			return err
		}
		if p.name == ForgeGitHub {
			if err := rejectGitLabOnlyInferenceKeys(p.name+".config", p.cfg.Config); err != nil {
				return err
			}
		}
		for i, entry := range p.cfg.Repos {
			field := fmt.Sprintf("%s.repos[%d].config", p.name, i)
			if entry.Name != "" {
				field = fmt.Sprintf("%s.repos[%s].config", p.name, entry.Name)
			}
			if err := validateManagedBlock(field, entry.Config); err != nil {
				return err
			}
			if p.name == ForgeGitHub {
				if err := rejectGitLabOnlyInferenceKeys(field, entry.Config); err != nil {
					return err
				}
			}
			if err := rejectAllowlistBelowReset([]allowlistLayer{
				{"defaults.config", m.Defaults.Config},
				{p.name + ".config", p.cfg.Config},
				{field, entry.Config},
			}); err != nil {
				return err
			}
			merged := m.mergeManagedConfig(p.cfg, entry)
			if err := config.ValidateMergedManaged(merged); err != nil {
				return fmt.Errorf("%s: merged managed configuration: %w", field, err)
			}
			if err := validateManagedMintAndWIF(merged); err != nil {
				return fmt.Errorf("%s: merged managed configuration: %w", field, err)
			}
		}
	}
	return nil
}

// allowlistLayer names one managed-configuration layer for
// rejectAllowlistBelowReset.
type allowlistLayer struct {
	field string
	cfg   config.ManagedConfig
}

// rejectAllowlistBelowReset refuses a non-empty allowed_remote_resources list
// declared in a more specific layer than an explicit empty list. An empty
// list resets the inherited allowlist (code defaults and any config_base
// preset prefixes included), but the sparse managed file flattens the
// layers and cannot record that reset: [] followed by [X] would flatten to
// [X], and the runtime would union the preset and code-default prefixes
// back in, admitting prefixes the declared layer chain excluded. layers are
// ordered least to most specific.
//
// The chain is evaluated as a whole: when the most specific declared list is
// itself empty, it supersedes every earlier layer (an empty → non-empty →
// empty chain resolves to deny-all and renders as []), so nothing is lost
// and the chain is accepted.
func rejectAllowlistBelowReset(layers []allowlistLayer) error {
	for i := len(layers) - 1; i >= 0; i-- {
		if list, declared := layers[i].cfg.ExplicitAllowedRemoteResources(); declared {
			if len(list) == 0 {
				return nil
			}
			break
		}
	}
	reset := ""
	for _, l := range layers {
		list, declared := l.cfg.ExplicitAllowedRemoteResources()
		if !declared {
			continue
		}
		if len(list) == 0 {
			reset = l.field
			continue
		}
		if reset != "" {
			return fmt.Errorf("%s.allowed_remote_resources: a non-empty list cannot be declared below the explicit empty list in %s.allowed_remote_resources: the empty list resets inherited prefixes and the managed file cannot record that reset; declare the full list in one layer instead", l.field, reset)
		}
	}
	return nil
}

// validateManagedBlock validates a single managed-configuration layer
// (defaults.config, a forge section's config, or one repository's raw
// config block) in isolation, before the layers are merged. It
// intentionally does not run the checks that need that merge (agent
// allowlist, override-only custom agents) — see config.ValidateManagedLayer — those run again, correctly,
// against the merged managed configuration below.
func validateManagedBlock(field string, o config.ManagedConfig) error {
	if !o.IsSet() {
		return nil
	}
	if err := config.ValidateManagedLayer(o.Writer()); err != nil {
		return fmt.Errorf("%s: %w", field, err)
	}
	if err := validateManagedMintAndWIF(o.Writer()); err != nil {
		return fmt.Errorf("%s: %w", field, err)
	}
	if err := ValidateAllowedRemoteResourcesFormat(field+".allowed_remote_resources", o.Writer().AllowedResources()); err != nil {
		return err
	}
	return nil
}

// validateManagedMintAndWIF runs the same mint_url HTTPS/userinfo gate
// used for RepoEntry.MintURL and the CLI's validateMintURLHTTPS, plus the
// WIF provider resource-name pattern check and the inference.wif_audience
// and inference.service_account format checks, on a managed-configuration
// layer or the merged result. The same check is correct whether r is an
// isolated layer or the merged configuration; an unset value resolves
// through the parent chain to the code default (always a valid HTTPS mint
// URL), so this only ever flags a value the managed configuration itself
// set. Install and converge write these values into the managed
// `.fullsend/config.yaml`; this closes the format gate before that write.
// Unlike github.url/gitlab.url (validated via RejectExtraneousURLParts),
// mint_url is allowed to carry a path — e.g. a Cloud Functions mint
// endpoint — matching every other mint_url gate in this codebase.
func validateManagedMintAndWIF(r config.PerRepoConfigReader) error {
	if err := validateDeclaredMintURL(r.ConfigMintURL()); err != nil {
		return err
	}
	if wif := r.ConfigInferenceWIFProvider(); wif != "" && !WIFProviderPattern.MatchString(wif) {
		return fmt.Errorf("inference.wif_provider %q does not match the required resource name pattern", wif)
	}
	return validateExistingWIFOptionFormats(r.ConfigInferenceWIFAudience(), r.ConfigInferenceServiceAccount())
}

// validateDeclaredMintURL applies the mint_url HTTPS/userinfo gate to a
// declared value; an empty value is accepted (nothing is declared). It is
// shared by managed-configuration validation and by the effective
// infrastructure resolution, which also receives mint_url from a
// config_base preset.
func validateDeclaredMintURL(mintURL string) error {
	if mintURL == "" {
		return nil
	}
	mu, err := url.Parse(mintURL)
	if err != nil || mu.Scheme != "https" || mu.Host == "" {
		return fmt.Errorf("mint_url must be a valid HTTPS URL, got %q", mintURL)
	}
	if mu.User != nil {
		return fmt.Errorf("mint_url must not contain userinfo, got %q", mintURL)
	}
	return nil
}

// ValidateAllowedRemoteResourcesFormat checks that every entry in an
// allowed_remote_resources allowlist (a repos.yaml config layer, or the
// merged managed configuration file) is a well-formed prefix: a valid
// HTTPS URL, ending with "/", with no double-encoded sequences. These are the same format rules
// harness.ValidateAllowedRemoteResources applies at `fullsend run`/`lock`
// time; that check runs too late to guard this write path, since
// MatchingAllowedPrefixInList does a plain strings.HasPrefix match and a
// prefix missing its trailing slash can therefore match sibling
// hosts/paths it should not. It does not check coverage against an
// config-level allowlist — that requires the harness, which is not loaded
// here. Manifest.Validate applies it to every config layer on
// load/converge, before anything is written.
func ValidateAllowedRemoteResourcesFormat(field string, list []string) error {
	for i, entry := range list {
		if !urlutil.IsURL(entry) {
			return fmt.Errorf("%s[%d]: %q is not a valid HTTPS URL", field, i, entry)
		}
		if !strings.HasSuffix(entry, "/") {
			return fmt.Errorf("%s[%d]: %q must end with /", field, i, entry)
		}
		if strings.Contains(strings.ToLower(entry), "%25") {
			return fmt.Errorf("%s[%d]: %q contains double-encoded sequence", field, i, entry)
		}
	}
	return nil
}
