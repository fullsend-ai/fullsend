func TestRunReposInstall_ForbiddenShorthandInConfig(t *testing.T) {
	tests := []struct {
		name    string
		yaml    string
		wantErr string
	}{
		{
			name: "runtime inside defaults.config",
			yaml: `version: 1
defaults:
  config:
    runtime: pi
github:
  mint_url: https://mint.example.com
  fullsend_ref: v1.0.0
  repos:
    - name: acme/api
`,
			wantErr: "runtime is not allowed inside config",
		},
		{
			name: "allowed_remote_resources inside repo config",
			yaml: `version: 1
github:
  mint_url: https://mint.example.com
  fullsend_ref: v1.0.0
  repos:
    - name: acme/api
      config:
        allowed_remote_resources: []
`,
			wantErr: "allowed_remote_resources is not allowed inside config",
		},
		{
			name: "unknown field",
			yaml: `version: 1
github:
  mint_url: https://mint.example.com
  fullsend_ref: v1.0.0
  repos:
    - name: acme/api
      config:
        bogus: true
`,
			wantErr: `unknown field "bogus"`,
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			manifestPath := writeTestManifest(t, tt.yaml)
			fc := newInstallFakeClient("acme/api")
			err := runReposInstall(context.Background(), githubManagedInstallOpts(manifestPath, fc))
			require.Error(t, err)
			assert.Contains(t, err.Error(), tt.wantErr)

			_, statusErr := statusJSON(t, manifestPath, fc)
			require.Error(t, statusErr)
			assert.Contains(t, statusErr.Error(), tt.wantErr)
		})
	}
}

func TestRunRepos_GitLabManagedConfigStatusAndDryRun(t *testing.T) {
	manifestPath := writeTestManifest(t, gitlabManagedManifestYAML)
	fc := newGitLabInstalledFake("group/project")
	drifted := []byte(managedConfigMarker + "kill_switch: false\n")
	fc.FileContents[overlayPath("group/project")] = drifted

	result, err := statusJSON(t, manifestPath, fc)
	require.Error(t, err)
	d, found := overlayDrift(t, result, "group/project")
	require.True(t, found, "GitLab status must report managed-configuration drift, got %s", mustEncode(t, result))
	assert.Equal(t, "managed configuration", d.Expected)

	require.NoError(t, runReposInstall(context.Background(), &reposInstallConfig{
		manifest:    manifestPath,
		concurrency: 4,
		dryRun:      true,
		testClient:  fc,
	}))
	assert.Equal(t, drifted, fc.FileContents[overlayPath("group/project")], "GitLab dry-run must not rewrite managed configuration")
}

func newGitLabInstalledFake(repo string) *forge.FakeClient {
	fc := forge.NewFakeClient()
	seedGitLabInputPrerequisites(fc, repo, "v1.0.0")
	fc.InstallationToken = true
	fc.AuthenticatedUser = "fullsend-app[bot]"
	fc.CollaboratorPermissions = map[string]string{
		repo + "/fullsend-app[bot]": "write",
	}
	parts := strings.SplitN(repo, "/", 2)
	fc.Repos = []forge.Repository{{
		FullName:      repo,
		Name:          parts[1],
		DefaultBranch: "main",
	}}
	fc.Secrets[repo+"/"+forge.SecretForgeToken] = true
	fc.Secrets[repo+"/"+forge.SecretOpenAIAPIKey] = true
	fc.PipelineSchedules[repo] = []forge.PipelineSchedule{
		{ID: 1, Description: "fullsend slash poll", Active: true},
		{ID: 2, Description: "fullsend event poll", Active: true},
	}
	fc.FileContents[repo+"/.gitlab/ci/fullsend-pipeline.yml"] = []byte("---\n# fullsend-ref: v1.0.0\n  ref: v1.0.0\n")
	return fc
}

func mustEncode(t *testing.T, v any) string {
	t.Helper()
	b, err := json.Marshal(v)
	require.NoError(t, err)
	return string(b)
}
