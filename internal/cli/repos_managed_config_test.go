func overlayPath(repo string) string {
	return repo + "/" + preset.OverlayPath
}

func githubManagedInstallOpts(manifestPath string, fc *forge.FakeClient) *reposInstallConfig {
	return &reposInstallConfig{
		manifest:               manifestPath,
		concurrency:            4,
		roles:                  []string{"triage"},
		direct:                 true,
		inferenceProject:       "inf-proj",
		inferenceProjectNumber: "123456789",
		inferenceRegion:        "us-central1",
		testClient:             fc,
	}
}

// useOpenAIInputs swaps the helper's default Vertex inputs for an OpenAI
// key; Converge rejects input groups that no selected repository consumes.
//
// Converge fails closed when it cannot fetch an explicit pin's scaffold to
// verify the OpenAI credential contract, so the fake upstream also serves a
// shim at the v1.0.0 and v2.0.0 pins these tests use that forwards the key.
func useOpenAIInputs(opts *reposInstallConfig) *reposInstallConfig {
	if fc, ok := opts.testClient.(*forge.FakeClient); ok {
		shim, err := scaffold.PerRepoShimTemplate()
		if err != nil {
			panic(err)
		}
		for _, ref := range []string{"v1.0.0", "v2.0.0"} {
			fc.FileContentsRef["fullsend-ai/fullsend/internal/scaffold/fullsend-repo/templates/shim-per-repo.yaml@"+ref] = shim
		}
	}
	opts.inferenceProject = ""
	opts.inferenceProjectNumber = ""
	opts.inferenceRegion = ""
	opts.openAIAPIKey = "test-openai-key"
	return opts
}

func statusJSON(t *testing.T, manifestPath string, fc forge.Client) (repos.StatusResult, error) {
	t.Helper()
	cmd := newReposStatusCmd()
	cmd.SetContext(context.Background())
	var buf bytes.Buffer
	cmd.SetOut(&buf)
	err := runReposStatus(cmd, &reposStatusConfig{
		manifest:    manifestPath,
		jsonOutput:  true,
		concurrency: 4,
		testClient:  fc,
	})
	var result repos.StatusResult
	out := buf.String()
	if out != "" {
		require.NoError(t, json.Unmarshal([]byte(out), &result), "status JSON: %s", out)
	}
	return result, err
}

func overlayDrift(t *testing.T, result repos.StatusResult, repo string) (repos.Drift, bool) {
	t.Helper()
	for _, rs := range result.Repos {
		if rs.Owner+"/"+rs.Repo != repo {
			continue
		}
		for _, d := range rs.Drifts {
			if d.Field == preset.OverlayPath {
				return d, true
			}
		}
	}
	return repos.Drift{}, false
}

func TestRunRepos_ManagedConfigPublicContract(t *testing.T) {
	manifestPath := writeTestManifest(t, githubManagedManifestYAML)
	fc := newInstallFakeClient("acme/api")

	require.NoError(t, runReposInstall(context.Background(), githubManagedInstallOpts(manifestPath, fc)))

	overlay := fc.FileContents[overlayPath("acme/api")]
	require.NotEmpty(t, overlay, "fresh managed install must write .fullsend/config.yaml")
	assert.True(t, bytes.HasPrefix(overlay, []byte(managedConfigMarker)), "ownership marker missing:\n%s", overlay)
	assert.Contains(t, string(overlay), "kill_switch: true")
	assert.NotContains(t, string(overlay), "roles:", "managed configuration must stay sparse")

	result, err := statusJSON(t, manifestPath, fc)
	require.NoError(t, err)
	if d, found := overlayDrift(t, result, "acme/api"); found {
		t.Fatalf("status reported managed-configuration drift immediately after install: %+v", d)
	}

	drifted := []byte(managedConfigMarker + "kill_switch: false\n")
	fc.FileContents[overlayPath("acme/api")] = drifted

	result, err = statusJSON(t, manifestPath, fc)
	require.Error(t, err, "status must be non-zero when managed configuration drifted")
	d, found := overlayDrift(t, result, "acme/api")
	require.True(t, found, "status must report .fullsend/config.yaml drift, got %s", mustEncode(t, result))
	assert.Equal(t, "managed configuration", d.Expected)
	assert.Equal(t, "installed content differs", d.Actual)

	require.NoError(t, runReposInstall(context.Background(), &reposInstallConfig{
		manifest:    manifestPath,
		concurrency: 4,
		dryRun:      true,
		testClient:  fc,
	}))
	assert.Equal(t, drifted, fc.FileContents[overlayPath("acme/api")], "dry-run must not rewrite managed configuration")

	require.NoError(t, runReposInstall(context.Background(), githubManagedInstallOpts(manifestPath, fc)))
	assert.Equal(t, overlay, fc.FileContents[overlayPath("acme/api")], "converge must restore the canonical managed file")

	result, err = statusJSON(t, manifestPath, fc)
	require.NoError(t, err)
	if d, found := overlayDrift(t, result, "acme/api"); found {
		t.Fatalf("status still reports managed-configuration drift after converge: %+v", d)
	}
}

