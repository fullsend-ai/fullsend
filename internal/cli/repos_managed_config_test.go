// managedConfigMarker is the public ADR-0122 ownership marker written at
// the start of every managed .fullsend/config.yaml. Command-level tests
// assert this contract rather than importing the unexported constant.
const managedConfigMarker = "# This file is managed by 'fullsend repos': repos-config-v1\n" +
	"# Do not edit this file directly; changes will be overwritten.\n"

