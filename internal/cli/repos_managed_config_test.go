func TestRunReposInstall_ForbiddenShorthandInConfig(t *testing.T) {
	tests := []struct {
		name    string
		yaml    string
		wantErr string
	}{
		{
			name: "runtime inside defaults.config",
			yaml: `version: 1
defaults:
  config:
    runtime: pi
github:
  mint_url: https://mint.example.com
  fullsend_ref: v1.0.0
  repos:
    - name: acme/api
`,
			wantErr: "runtime is not allowed inside config",
		},
		{
			name: "allowed_remote_resources inside repo config",
			yaml: `version: 1
github:
  mint_url: https://mint.example.com
  fullsend_ref: v1.0.0
  repos:
    - name: acme/api
      config:
        allowed_remote_resources: []
`,
			wantErr: "allowed_remote_resources is not allowed inside config",
		},
		{
			name: "unknown field",
			yaml: `version: 1
github:
  mint_url: https://mint.example.com
  fullsend_ref: v1.0.0
  repos:
    - name: acme/api
      config:
        bogus: true
`,
			wantErr: `unknown field "bogus"`,
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			manifestPath := writeTestManifest(t, tt.yaml)
			fc := newInstallFakeClient("acme/api")
			err := runReposInstall(context.Background(), githubManagedInstallOpts(manifestPath, fc))
			require.Error(t, err)
			assert.Contains(t, err.Error(), tt.wantErr)

			_, statusErr := statusJSON(t, manifestPath, fc)
			require.Error(t, statusErr)
			assert.Contains(t, statusErr.Error(), tt.wantErr)
		})
	}
}

